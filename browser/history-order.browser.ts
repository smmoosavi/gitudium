import { test, expect, id, summary } from "./fixtures";

test("order settings retain selection beyond a page, navigate display order and persist", async ({ page, repository }) => {
  repository.historyCommits = Array.from({ length: 260 }, (_, index) => ({ ...summary(index), parents: [] }));
  repository.historyTimestamps = new Map(repository.historyCommits.map((commit, index) => [commit.id, index]));
  await page.reload();
  const first = page.locator(`[data-commit-id="${id(0)}"]`);
  await first.click();
  const selectedFile = page.locator('.files button[title="b.txt"]');
  await selectedFile.click();
  const gear = page.getByRole("button", { name: "Log settings", exact: true });
  await gear.click();
  await expect(page.getByLabel("Order", { exact: true })).toHaveValue("structural");
  await page.getByLabel("Order", { exact: true }).selectOption("recent");
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  await gear.click();
  await expect(page.getByLabel("Order", { exact: true })).toHaveValue("structural");
  await page.getByLabel("Order", { exact: true }).selectOption("recent");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(first).toHaveAttribute("data-commit-index", "259");
  await expect(first).toHaveAttribute("aria-pressed", "true");
  await expect(first).toBeInViewport();
  await expect(gear).toBeFocused();
  await expect(selectedFile).toHaveAttribute("aria-pressed", "true");
  const continuations = repository.requests.filter(request => request.method === "history" && (request.input?.cursor as { snapshot?: string } | undefined)?.snapshot === "fixture-recent");
  expect(continuations.length).toBeGreaterThanOrEqual(2);
  expect(continuations.every(request => request.input?.order === undefined)).toBe(true);
  await first.click();
  await page.keyboard.press("ArrowUp");
  await expect(page.locator(`[data-commit-id="${id(1)}"]`)).toHaveAttribute("aria-pressed", "true");
  await page.reload();
  await expect(page.locator('[data-commit-index="0"]')).toHaveAttribute("data-commit-id", id(259));
  await gear.click();
  await expect(page.getByLabel("Order", { exact: true })).toHaveValue("recent");
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  await page.getByRole("button", { name: /Local changes/ }).click();
  await gear.click();
  await page.getByLabel("Order", { exact: true }).selectOption("structural");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(page.getByRole("button", { name: /Local changes/ })).toHaveAttribute("aria-pressed", "true");
});

test("a selected commit awaiting recent pages survives pagination errors and retry", async ({ page, repository }) => {
  repository.historyCommits = Array.from({ length: 260 }, (_, index) => ({ ...summary(index), parents: [] }));
  repository.historyTimestamps = new Map(repository.historyCommits.map((commit, index) => [commit.id, index]));
  await page.reload();
  await page.locator(`[data-commit-id="${id(0)}"]`).click();
  await expect(page.locator(".commit-summary h3")).toHaveText("Fixture commit 0");
  repository.failPagination = true;
  repository.paginationAttempts = 0;
  const gear = page.getByRole("button", { name: "Log settings", exact: true });
  await gear.click();
  await page.getByLabel("Order", { exact: true }).selectOption("recent");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("Fixture pagination failed");
  await expect(page.locator(".commit-summary h3")).toHaveText("Fixture commit 0");
  await expect(page.locator('.commits button[aria-pressed="true"]')).toHaveCount(0);
  await expect(gear).toBeFocused();
  await page.getByRole("button", { name: "Retry", exact: true }).click();
  await expect(page.locator(`[data-commit-id="${id(0)}"]`)).toHaveAttribute("aria-pressed", "true");
  await expect(page.locator(".commit-summary h3")).toHaveText("Fixture commit 0");
});
